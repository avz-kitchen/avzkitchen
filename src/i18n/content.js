export const getLocaleFromPath = (pathname = "/") =>
  pathname.startsWith("/de") ? "de" : "en";

export const getLocalizedPath = (pathname = "/", locale = "en") => {
  const cleanPath = pathname.startsWith("/de") ? pathname.replace(/^\/de/, "") || "/" : pathname || "/";

  if (locale === "de") {
    return cleanPath === "/" ? "/de" : `/de${cleanPath}`;
  }

  return cleanPath;
};

export const getUiText = (locale, section, key) => {
  const current = uiContent[locale] || uiContent.en;
  return current[section]?.[key] ?? uiContent.en[section]?.[key] ?? "";
};